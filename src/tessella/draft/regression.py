"""Regression tests from approved probe findings (pytest + httpx)."""

from __future__ import annotations

import json

from tessella.models import Case, Draft, DraftKind

_TEMPLATE = '''"""Regression test generated by Tessella from an approved finding: {title}"""
import httpx

BASE_URL = "{base_url}"


def test_{name}():
    with httpx.Client(base_url=BASE_URL) as c:
{steps}
        # Expected: fix the bug, then assert the correct behaviour here.
        assert last.status_code < 500
'''


def regression_test(case: Case, base_url: str) -> Draft:
    assert case.flow is not None
    lines = []
    for s in case.flow.steps:
        body = f", json={json.dumps(s.body)}" if s.body is not None else ""
        lines.append(f'        last = c.request("{s.method}", "{s.url}"{body})')
    name = "".join(ch if ch.isalnum() else "_" for ch in case.title.lower())[:60]
    code = _TEMPLATE.format(title=case.title, base_url=base_url, name=name, steps="\n".join(lines))
    return Draft(kind=DraftKind.regression_test, title=f"test_{name}.py", body=code)
